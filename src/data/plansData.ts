/**
 * Helper to generate calendar StructuredWorkout items when a user purchases a plan
 */
export function generateWorkoutsFromPlan(
  plan: PurchasablePlan,
  startDateStr: string // YYYY-MM-DD
): StructuredWorkout[] {
  const result: StructuredWorkout[] = [];
  const start = new Date(startDateStr);

  // We generate up to 4 weeks of structured daily workouts to immediately populate the calendar
  const weeksToGenerate = Math.min(plan.durationWeeks, 4);

  for (let w = 0; w < weeksToGenerate; w++) {
    const weekOutline = plan.weeklyStructure[w] || plan.weeklyStructure[0];

    plan.workoutsTemplate.forEach((tmpl, idx) => {
      // Calculate date
      const daysToAdd = w * 7 + tmpl.dayOffset;
      const workoutDate = new Date(start);
      workoutDate.setDate(start.getDate() + daysToAdd);
      const dateString = workoutDate.toISOString().split('T')[0];

      result.push({
        id: `purchased-${plan.id}-w${w + 1}-d${tmpl.dayOffset}-${idx}`,
        date: dateString,
        title: `[${plan.title.split(':')[0]}] W${w + 1}: ${tmpl.title}`,
        sport: tmpl.sport,
        plannedDurationMinutes: tmpl.durationMinutes,
        plannedTSS: tmpl.plannedTSS,
        description: `${tmpl.description}. Coach: ${plan.coach.name}. Week Focus: ${weekOutline.focus}`,
        structure: [
          { phase: 'Warmup', durationMinutes: 15, targetZone: 'Z2 Aerobic', targetDescription: 'Progressive build' },
          { phase: 'Main Work', durationMinutes: Math.max(15, tmpl.durationMinutes - 25), targetZone: tmpl.targetZone, targetDescription: tmpl.description },
          { phase: 'Cooldown', durationMinutes: 10, targetZone: 'Z1 Flush', targetDescription: 'Spin down easy' },
        ],
        isCompleted: false,
      });
    });
  }

  return result;
}
