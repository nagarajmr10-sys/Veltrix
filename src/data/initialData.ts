// Helper to generate realistic GPS track
function generateTrack(
  startLat: number,
  startLon: number,
  baseEle: number,
  count: number,
  eleGain: number,
  avgSpeedMps: number,
  avgWatts: number,
  avgHr: number
) {
  const points = [];
  let currentLat = startLat;
  let currentLon = startLon;
  let currentEle = baseEle;
  const now = Date.now() - 3600 * 1000 * 3;

  for (let i = 0; i < count; i++) {
    const fraction = i / count;
    const angle = fraction * Math.PI * 2;
    currentLat = startLat + 0.02 * Math.sin(angle) + 0.005 * Math.sin(angle * 3);
    currentLon = startLon + 0.03 * Math.cos(angle) + 0.008 * Math.cos(angle * 2);
    currentEle = baseEle + eleGain * Math.pow(Math.sin(fraction * Math.PI), 1.5) + (Math.random() * 2 - 1);

    const speed = avgSpeedMps + (Math.random() * 1.6 - 0.8);
    const power = avgWatts > 0 ? Math.round(avgWatts + (Math.random() * 40 - 20) + (fraction > 0.3 && fraction < 0.7 ? 45 : -10)) : undefined;
    const hr = Math.round(avgHr + (Math.random() * 8 - 4) + (fraction > 0.4 ? 10 : 0));

    points.push({
      latitude: Number(currentLat.toFixed(6)),
      longitude: Number(currentLon.toFixed(6)),
      altitude: Number(currentEle.toFixed(1)),
      speed: Number(speed.toFixed(2)),
      heartRate: hr,
      cadence: avgWatts > 0 ? Math.round(88 + Math.random() * 8 - 4) : Math.round(174 + Math.random() * 6 - 3),
      power: power,
      timestamp: now + i * 15 * 1000,
    });
  }
  return points;
}

