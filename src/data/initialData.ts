// 42-day rolling historical PMC metrics (TrainingPeaks Performance Management Chart)
export function generateHistoricalPMC(): DailyTrainingMetric[] {
  const metrics: DailyTrainingMetric[] = [];
  const totalDays = 45;
  const now = new Date();

  // Starting values 45 days ago
  let ctl = 68; // Fitness
  let atl = 74; // Fatigue

  const workoutSchedule: { [offset: number]: { tss: number; title: string; sport: Activity['sport']; km: number } } = {
    0: { tss: 198, title: 'Marin Headlands Epic', sport: 'gravel', km: 64.8 },
    1: { tss: 88, title: 'Threshold 12K Surges', sport: 'running', km: 12.4 },
    2: { tss: 0, title: 'Rest & Mobility', sport: 'cycling', km: 0 },
    3: { tss: 145, title: 'Tempo 75km Road Ride', sport: 'cycling', km: 75.2 },
    4: { tss: 112, title: 'VO2 Max 5x1km Track', sport: 'running', km: 14.0 },
    5: { tss: 215, title: 'Weekend Century 120km', sport: 'cycling', km: 122.0 },
    6: { tss: 165, title: 'Long Trail Run 24km', sport: 'trail_running', km: 24.5 },
    7: { tss: 0, title: 'Active Recovery Flush', sport: 'cycling', km: 0 },
    8: { tss: 95, title: 'Sweet Spot 3x15min', sport: 'cycling', km: 48.0 },
    9: { tss: 78, title: 'Aerobic Base 10K', sport: 'running', km: 10.2 },
    10: { tss: 135, title: 'Pyrenees Climb Simulation', sport: 'cycling', km: 62.0 },
    11: { tss: 0, title: 'Rest Day', sport: 'running', km: 0 },
    12: { tss: 180, title: 'Over-Under Intervals 80km', sport: 'cycling', km: 80.0 },
    13: { tss: 140, title: 'Half Marathon Progression', sport: 'running', km: 21.1 },
    14: { tss: 45, title: 'Easy Spin 20km', sport: 'cycling', km: 20.0 },
  };

  for (let i = totalDays; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 86400 * 1000);
    const dateStr = d.toISOString().split('T')[0];

    let tss = 0;
    let workoutInfo = undefined;

    if (workoutSchedule[i]) {
      tss = workoutSchedule[i].tss;
      workoutInfo = workoutSchedule[i];
    } else {
      // Procedural realistic training load
      const dayOfWeek = d.getDay();
      if (dayOfWeek === 1) {
        tss = 0; // Monday rest
      } else if (dayOfWeek === 6 || dayOfWeek === 0) {
        tss = Math.round(140 + Math.random() * 80); // Weekend big volume
      } else {
        tss = Math.round(60 + Math.random() * 70); // Midweek quality
      }
    }

    // Exponential moving averages:
    // CTL = CTL_prev + (TSS - CTL_prev) * (1 - e^(-1/42)) ~ (TSS - CTL_prev)/42
    // ATL = ATL_prev + (TSS - ATL_prev) * (1 - e^(-1/7)) ~ (TSS - ATL_prev)/7
    ctl = ctl + (tss - ctl) / 42;
    atl = atl + (tss - atl) / 7;
    const tsb = Math.round(ctl - atl); // Form

    metrics.push({
      date: dateStr,
      tss,
      ctl: Math.round(ctl * 10) / 10,
      atl: Math.round(atl * 10) / 10,
      tsb,
      workoutTitle: workoutInfo?.title,
      workoutSport: workoutInfo?.sport,
      workoutDistanceKm: workoutInfo?.km,
    });
  }

  return metrics;
}

